export type Lang = 'nb' | 'en';
export const dictionaries: Record<Lang, Record<StringKey, string>> = { nb, en };

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? nb[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export type TFn = (key: StringKey, params?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  return (key, params) => translate(lang, key, params);
}
