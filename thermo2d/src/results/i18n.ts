export const RESULTS_STRINGS: Record<'nb' | 'en', Record<ResultsStringKey, string>> = { nb, en };

export type TFn = (key: ResultsStringKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: 'nb' | 'en'): TFn {
  const dict = RESULTS_STRINGS[lang] ?? nb;
  return (key, vars) => {
    let s: string = dict[key] ?? nb[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}
